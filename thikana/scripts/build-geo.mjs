// Converts the nuhil/bangladesh-geocode PHPMyAdmin JSON exports into the compact
// files the app ships: src/data/bd-geo.json and supabase/districts.sql.
// Usage: node scripts/build-geo.mjs <dir containing districts.json upazilas.json unions.json>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-geo.mjs <dataset-dir>");
  process.exit(1);
}

// Known typos in the upstream dataset, by "<table>:<id>".
const FIXES = { "unions:1822": "আদাবাড়িয়া" };

// The dataset mixes precomposed and decomposed Bangla letters (e.g. য়); normalise
// so names compare and sort the same way as text people type.
const bn = (table, x) => (FIXES[`${table}:${x.id}`] ?? x.bn_name).normalize("NFC");

const table = (name) =>
  JSON.parse(readFileSync(join(src, `${name}.json`), "utf8")).find((x) => x.type === "table").data;

const districts = table("districts").map((d) => ({
  id: d.id,
  en: d.name,
  bn: bn("districts", d),
  lat: Number(d.lat),
  lon: Number(d.lon),
}));
const upazilas = table("upazilas").map((u) => ({ id: u.id, d: u.district_id, en: u.name, bn: bn("upazilas", u) }));
const unions = table("unions").map((u) => ({ id: u.id, u: u.upazilla_id, en: u.name, bn: bn("unions", u) }));

writeFileSync("src/data/bd-geo.json", JSON.stringify({ districts, upazilas, unions }));

const rows = districts.map((d) => `  (${d.id}, '${d.en.replace(/'/g, "''")}', ${d.lat}, ${d.lon})`).join(",\n");
writeFileSync(
  "supabase/districts.sql",
  `-- Generated by scripts/build-geo.mjs. District centres used to compute delivery time.\n` +
    `insert into public.districts (id, name, lat, lon) values\n${rows}\non conflict (id) do update set name = excluded.name, lat = excluded.lat, lon = excluded.lon;\n`,
);

console.log(`districts=${districts.length} upazilas=${upazilas.length} unions=${unions.length}`);
